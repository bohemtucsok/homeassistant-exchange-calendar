"""Pure helpers for Exchange event normalization and time comparison.

This module deliberately has no Home Assistant imports so the logic can be
unit-tested without a Home Assistant installation (see ``tests/``).
``calendar.py`` wraps these helpers with the HA default timezone.
"""
from __future__ import annotations

import struct
from datetime import date, datetime, time, timedelta, tzinfo
from typing import Any

DEFAULT_MAX_SUMMARY_LENGTH = 255
DEFAULT_MAX_DESCRIPTION_LENGTH = 4000

# PidLidGlobalObjectId layout (MS-OXOCAL 2.2.1.27): a fixed 16-byte header,
# exception replacement time (4), creation time (8), reserved (8), the payload
# length (little-endian uint32) and the payload itself.
GLOBAL_OBJECT_ID_HEADER = bytes.fromhex("040000008200E00074C5B7101A82E008")
# iCalendar UIDs generated by Outlook/Exchange are the hex encoding of the
# object id itself, so they start with the header.
OUTLOOK_UID_PREFIX = GLOBAL_OBJECT_ID_HEADER.hex().upper()
_VCAL_UID_MARKER = b"vCal-Uid\x01\x00\x00\x00"


def uid_to_global_object_id(uid: str | None) -> bytes | None:
    """Encode an iCalendar UID as the PidLidGlobalObjectId binary value.

    EWS cannot filter on ``calendar:UID`` directly, but it can filter on the
    GlobalObjectId extended property. Two UID flavours exist:

    - Outlook/Exchange-generated UIDs are the hex of the object id: decode
      them as-is (what exchangelib's ``UID.to_global_object_id`` does).
    - Any other UID (e.g. one created by this integration) is wrapped in the
      ``vCal-Uid`` envelope (what exchangelib's ``UID(...)`` does).

    Returns ``None`` when the UID cannot be encoded.
    """
    uid = (uid or "").strip()
    if not uid:
        return None
    if uid.upper().startswith(OUTLOOK_UID_PREFIX) and len(uid) % 2 == 0:
        try:
            return bytes.fromhex(uid)
        except ValueError:
            pass
    try:
        payload = _VCAL_UID_MARKER + uid.encode("ascii") + b"\x00"
    except UnicodeEncodeError:
        return None
    return (
        GLOBAL_OBJECT_ID_HEADER
        + bytes(4)  # exception replacement time
        + bytes(8)  # creation time
        + bytes(8)  # reserved
        + struct.pack("<I", len(payload))
        + payload
    )


def is_date(value: Any) -> bool:
    """Return True for a plain date (all-day bound), False for a datetime."""
    return isinstance(value, date) and not isinstance(value, datetime)


def start_of_day(value: date | datetime, tz: tzinfo) -> datetime:
    """Return the tz-aware midnight of ``value``'s calendar day in ``tz``.

    A tz-aware datetime is converted to ``tz`` first so the day is taken in
    the target zone; a naive datetime is assumed to already be in it.
    """
    if isinstance(value, datetime):
        if value.tzinfo is not None:
            value = value.astimezone(tz)
        value = value.date()
    return datetime.combine(value, time.min, tzinfo=tz)


def to_comparable_datetime(value: date | datetime, tz: tzinfo) -> datetime:
    """Convert a date or datetime to a tz-aware datetime for comparisons.

    All-day bounds (plain dates) map to local midnight; naive datetimes are
    assumed to be in ``tz``.
    """
    if isinstance(value, datetime):
        if value.tzinfo is None:
            return value.replace(tzinfo=tz)
        return value
    return start_of_day(value, tz)


def normalize_event(
    ev: dict[str, Any],
    tz: tzinfo,
    max_summary: int = DEFAULT_MAX_SUMMARY_LENGTH,
    max_description: int = DEFAULT_MAX_DESCRIPTION_LENGTH,
) -> dict[str, Any]:
    """Return a sanitized copy of an event dict. Idempotent.

    Guards against Exchange edge cases that break the HA calendar UI:

    - mixed date/datetime bounds -> the date side becomes local midnight;
    - naive datetimes -> assumed to be in ``tz``;
    - all-day events whose end is not exclusive (``end <= start``) -> the end
      becomes the next day, so the event actually spans its day;
    - timed events with ``end < start`` -> end clamped to start;
    - oversized summary/description -> truncated.

    Applying it twice yields the same result, so callers may normalize
    defensively at several layers.
    """
    ev = dict(ev)
    start = ev.get("start")
    end = ev.get("end")

    # Mixed date/datetime bounds -> promote the date side to local midnight
    # so both ends share a type (required by CalendarEvent).
    if is_date(start) and isinstance(end, datetime):
        start = start_of_day(start, tz)
    elif isinstance(start, datetime) and is_date(end):
        end = start_of_day(end, tz)

    # Naive datetimes -> assume the given timezone.
    if isinstance(start, datetime) and start.tzinfo is None:
        start = start.replace(tzinfo=tz)
    if isinstance(end, datetime) and end.tzinfo is None:
        end = end.replace(tzinfo=tz)

    # Inverted or degenerate ranges (seen on on-prem Exchange).
    if start is not None and end is not None:
        if is_date(start) and is_date(end):
            if end <= start:
                end = start + timedelta(days=1)  # all-day: exclusive end
        elif isinstance(start, datetime) and isinstance(end, datetime):
            if end < start:
                end = start

    ev["start"] = start
    ev["end"] = end

    summary = ev.get("summary") or "(No subject)"
    if len(summary) > max_summary:
        summary = summary[: max_summary - 3] + "..."
    ev["summary"] = summary

    description = ev.get("description") or ""
    if len(description) > max_description:
        description = description[: max_description - 3] + "..."
    ev["description"] = description

    return ev


def event_overlaps(
    ev: dict[str, Any], window_start: datetime, window_end: datetime, tz: tzinfo
) -> bool:
    """Return True if ``ev`` overlaps the half-open window [start, end).

    ``ev`` should already be normalized. An event ending exactly at
    ``window_start`` does not overlap; one starting exactly at it does.
    """
    start_dt = to_comparable_datetime(ev["start"], tz)
    end_dt = to_comparable_datetime(ev["end"], tz)
    return end_dt > window_start and start_dt < window_end
